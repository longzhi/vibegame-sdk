/// 一关接成一张地图：每行一样宽。
pub fn rows(l: &Level) -> Vec<String> {
    if l.vertical {
        return l.parts.iter().flat_map(|p| p.iter().map(|r| r.to_string())).collect();
    }
    let mut out = vec![String::new(); 10];
    for part in l.parts {
        for (i, r) in part.iter().enumerate() {
            out[i].push_str(r);
        }
    }
    out
}

