//! 四关的地图，自己画的。一关分几段，每段 10 行一样宽。
//! 横着的关把几段左右接起来；竖着的关（瀑布）把几段上下接起来，从最下面往上爬。
//!
//! 一个字符一格（16 像素）：
//! `.` 空　`#` 石头、土、铁墙（实心，上面空着就画成能站的顶）　`-` 台子（从下面跳得上来，按下加 A 跳下去）
//! `b` 桥（走上去一节一节炸掉）　`~` 水（站在里面只露上半身，按下潜下去）　`f` 喷火口（一阵一阵往上喷火）
//! `@` 起点　`t` 炮台（嵌在墙里，跟着人转）　`P` 地堡（一开一关，打坏了掉勋章）　`C` 补给舱（画面到了从左边飞过来）
//! `g` 端枪的兵　`h` 躲在沙袋后面的兵　`n` 扔手雷的兵　`k` 滚石头的地方　`T` 坦克　`X` 大怪
//! 兵、坦克写在它站的那格上面一格。
//!
//! 主角跳得到 2 格高、2 格远。

use crate::art::Theme;
use vibegame::full::lang;

pub struct Level {
    pub name: &'static str,
    /// 英文的关名。
    pub name_en: &'static str,
    pub theme: Theme,
    /// 竖着往上爬的关。
    pub vertical: bool,
    pub parts: &'static [[&'static str; 10]],
    /// 兵从画面边上一个一个跑出来的地段（第几列到第几列）。竖着的关不用。
    pub runners: &'static [(i32, i32)],
    /// 地堡和补给舱按出场的先后掉的勋章。
    pub drops: &'static str,
}

impl Level {
    /// 按系统语言出的关名。
    pub fn label(&self) -> &'static str {
        lang().pick(self.name_en, self.name)
    }
}

