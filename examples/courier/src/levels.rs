//! 六关的地图，自己画的。一关分几段，每段 10 行一样宽，读的时候接起来。
//!
//! 一个字符一格（16 像素）：
//! `.` 空　`#` 地面　`R` 砖墙（打不碎）　`S` 石块　`B` 旧木箱（大个子顶得碎）
//! `M` 包裹箱（一张邮票）　`P` 包裹箱（变大的包裹；已经大了出纸飞机）　`I` 包裹箱（金邮票）
//! `T` 旧木箱，连着顶出好几张邮票　`L` 看不见的箱子（多一条命）
//! `<` `>` 烟囱顶左右　`(` `)` 烟囱身左右　`~` 脏水、铁水（掉进去就没了）　`^` 地上的蒸汽口
//! `=` 横着走的踏板　`|` 上下走的踏板　`o` 邮票　`@` 起点　`D` 邮局的门（终点）　`K` 中途点
//! 敌人：`w` 发条兵　`k` 罐头虫　`r` 乌鸦　`s` 刺海胆　`c` 煤球（放在烟囱顶上面那格）　`X` 邮件大盗
//!
//! 主角站在第 7 行（地面是第 8、9 行）。小个子跳得到 4 格高，跑起来 5 格。

use crate::art::Theme;

pub struct Level {
    pub name: &'static str,
    pub theme: Theme,
    pub parts: &'static [[&'static str; 10]],
}

pub const LEVELS: [Level; 6] = [
    Level { name: "1-1 早班", theme: Theme::Street, parts: &L1 },
    Level { name: "1-2 下水道", theme: Theme::Sewer, parts: &L2 },
    Level { name: "1-3 屋顶", theme: Theme::Roof, parts: &L3 },
    Level { name: "2-1 夜港", theme: Theme::Harbor, parts: &L4 },
    Level { name: "2-2 夜屋顶", theme: Theme::NightRoof, parts: &L5 },
    Level { name: "2-3 钟楼", theme: Theme::Tower, parts: &L6 },
];

/// 一关接成一张地图：10 行，一样宽。
pub fn rows(l: &Level) -> Vec<String> {
    let mut out = vec![String::new(); 10];
    for part in l.parts {
        for (i, r) in part.iter().enumerate() {
            out[i].push_str(r);
        }
    }
    out
}

